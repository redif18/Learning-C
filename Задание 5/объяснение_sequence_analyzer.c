#include <stdio.h>

int main(void)
{
    /* ===== ПЕРЕМЕННЫЕ =====
       Тут мы просто "резервируем коробки" для будущих данных.
       Некоторые коробки сразу получают стартовое число (0),
       чтобы в них не было мусора, пока мы ничего туда не положили. */

    int n;
    /* n - сколько чисел введёт пользователь. Пока пустая коробка,
       заполнится через пару строк, когда прочитаем scanf. */

    int data[20];
    /* Массив - это 20 коробок подряд, каждая под одно число.
       Обращаемся к ним по номеру: data[0] - первая, data[1] - вторая,
       и так далее до data[19]. Мы используем только первые n коробок,
       остальные просто не трогаем. */

    int sum = 0;
    /* Тут будем копить сумму всех чисел. Начинаем с 0, потому что
       сумма пустого набора - это ноль, логичная точка отсчёта. */

    int min = 0;
    int max = 0;
    /* Это ВРЕМЕННЫЕ заглушки. Настоящие min/max мы поставим сюда
       чуть позже, как только прочитаем первое число (см. ниже,
       блок "if (i == 0)"). Эти нули живут только до первой итерации
       цикла и потом стираются. */

    int even = 0;
    /* Счётчик чётных чисел. Начинаем с 0, потому что пока мы не
       нашли ни одного чётного - логично, что счётчик пуст. */

    int inversions = 0;
    /* Счётчик "нарушений порядка". Тоже с нуля, посчитаем позже. */


    /* ===== TODO 1: считать n и проверить диапазон 1...20 ===== */

    if (scanf("%d", &n) != 1 || n < 1 || n > 20)
    {
        /* Условие в if читается как три отдельные проверки,
           соединённые "ИЛИ" (||) - то есть если ХОТЯ БЫ ОДНА
           из них верна, мы заходим внутрь {}:

           1) scanf("%d", &n) != 1
              scanf пытается прочитать одно целое число в n.
              Она возвращает, СКОЛЬКО чисел реально получилось
              прочитать. Если пользователь ввёл не число (буквы,
              пусто) - scanf вернёт не 1, и это условие станет верным.

           2) n < 1
              n меньше разрешённого минимума.

           3) n > 20
              n больше разрешённого максимума.

           Если сработало хоть одно - это ошибка ввода. */

        printf("input_error\n");
        /* Печатаем ровно то слово, что требует задание. */

        return 0;
        /* Немедленно завершаем программу. Всё, что ниже, уже не
           выполнится - ни цикл чтения массива, ни вычисления. */
    }

    /* Если мы дошли до этой точки (после if), значит проверка
       НЕ сработала - то есть n успешно прочитано и лежит в 1...20.
       Дальше можно спокойно пользоваться n. */


    /* ===== TODO 2: считать n чисел одним циклом ===== */

    for (int i = 0; i < n; i++)
    {
        /* Разбор цикла for по частям:
           - "int i = 0"   выполняется ОДИН раз, в самом начале:
                           создаём счётчик i, начинаем с нуля.
           - "i < n"       проверяется ПЕРЕД каждым повтором тела.
                           Пока верно - тело выполняется ещё раз.
           - "i++"         выполняется ПОСЛЕ каждого повтора тела:
                           увеличивает i на 1.

           Итог: тело цикла выполнится для i = 0, 1, 2, ..., n-1.
           Именно поэтому условие "i < n", а не "i <= n" - индексы
           массива из n элементов идут ровно от 0 до n-1, а data[n]
           уже не существует. */

        if (scanf("%d", &data[i]) != 1 || data[i] < -1000 || data[i] > 1000)
        {
            /* Та же идея, что и с n выше, только теперь:
               - читаем число прямо в ячейку data[i] (текущий индекс)
               - и диапазон другой: -1000...1000, как требует задание */

            printf("input_error\n");
            return 0;
            /* Важно: раз мы уже прочитали НЕДОПУСТИМОЕ число, мы
               его НИКУДА не добавляем - ни в sum, ни в min/max,
               ни в even. Просто сразу выходим. */
        }

        /* Если дошли сюда - data[i] точно годное число.
           Теперь можно его использовать в вычислениях. */

        sum = sum + data[i];
        /* Накопление: sum получает своё старое значение плюс
           только что прочитанное число. После всех итераций
           здесь будет сумма всех n чисел. */

        if (data[i] % 2 == 0)
        {
            /* % - это остаток от деления. Если число делится на 2
               без остатка (остаток равен 0), значит оно чётное. */

            even = even + 1;
            /* Нашли ещё одно чётное - увеличиваем счётчик на 1. */
        }

        if (i == 0)
        {
            /* Это САМОЕ ПЕРВОЕ число из введённых (индекс 0).
               Именно тут мы заменяем временные заглушки (min=0,
               max=0 из объявления) на настоящее первое число.
               Так min/max всегда стартуют с реального элемента
               последовательности, а не с выдуманного нуля, который
               мог бы там вообще не встречаться (например, если все
               числа положительные или все отрицательные). */

            min = data[i];
            max = data[i];
        }
        else
        {
            /* Для всех чисел, КРОМЕ первого, просто сравниваем
               с уже накопленными min/max: вдруг это число ещё
               меньше текущего min, или ещё больше текущего max. */

            if (data[i] < min)
            {
                min = data[i];
            }
            if (data[i] > max)
            {
                max = data[i];
            }
        }
    }
    /* Тут цикл заканчивается. К этому моменту массив data[0..n-1]
       полностью заполнен допустимыми числами, а sum, min, max,
       even уже полностью посчитаны. */


    /* ===== TODO 3: подсчёт инверсий вложенными циклами ===== */

    for (int i = 0; i < n - 1; i++)
    {
        /* Внешний цикл перебирает КАЖДЫЙ элемент как "левый".
           i идёт до n - 2 включительно (условие i < n - 1),
           потому что у самого последнего элемента (индекс n-1)
           уже нет никого справа, с кем сравнивать. */

        for (int j = i + 1; j < n; j++)
        {
            /* Внутренний цикл перебирает элементы СПРАВА от i.
               j начинается с i + 1, а НЕ с 0, по двум причинам:

               1) Если бы j начинался с 0, при j == i мы бы
                  сравнивали число само с собой - бессмысленно.

               2) Если бы j начинался с 0, при j < i мы бы повторно
                  сравнили пару, которую уже проверили раньше (когда
                  внешний цикл проходил именно это j), только в
                  обратном порядке. Условие j = i + 1 гарантирует,
                  что каждая пара (i, j) с i < j проверяется РОВНО
                  ОДИН РАЗ. */

            if (data[i] > data[j])
            {
                /* Строго ">" (не ">="), потому что инверсия - это
                   именно НАРУШЕНИЕ порядка: левое число больше
                   правого. Если числа равны, порядок не нарушен,
                   поэтому равенство не считается инверсией. */

                inversions = inversions + 1;
            }
        }
    }


    /* ===== TODO 4: вывод результата ===== */

    printf("sum = %d\n", sum);
    printf("min = %d\n", min);
    printf("max = %d\n", max);
    printf("even = %d\n", even);
    printf("inversions = %d\n", inversions);
    /* Пять строк, ровно в этом порядке и с этими именами - так,
       как требует задание. Эти строки выполнятся, только если
       программа НЕ вышла раньше через return 0 в одной из проверок
       выше - то есть только когда все данные оказались корректными. */

    return 0;
    /* Обычное, "штатное" завершение программы - всё прошло успешно. */
}