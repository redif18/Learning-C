#include <stdio.h>

int main(void)
{
    int year = 2026; /* вводим переменную заглушку, чтобы не было ошибок, или если код получит неверную перменную, чтобы он вывел это значение */
    scanf("%d", &year); /* вводим свою перменную %d это целое число, затем обязательно , а потом сама перменная, в данном случае year и перед перменной обязательно & */
    printf("%d\n", year); /* а теперь выводим само значение, тут правило такое же как и у scanf*/
    return 0;
}